export function summaryFingerprint(summary: string) {
  return createHash("sha1").update(summary.replace(/\s+/g, "")).digest("hex").slice(0, 12);
}

/** 回傳改寫後的內容與實際改了幾個行程；沒有需要改的就回傳原本的物件。 */
export function applySummaryRewrites(content: SiteContent): { content: SiteContent; changed: number } {
  const bySlug = new Map(rewrites.map(([slug, fingerprint, summary]) => [slug, { fingerprint, summary }]));
  let changed = 0;
  const trips = content.trips.map((trip) => {
    const rewrite = bySlug.get(trip.slug || trip.id);
    if (!rewrite || summaryFingerprint(trip.summary) !== rewrite.fingerprint) return trip;
    changed += 1;
    return { ...trip, summary: rewrite.summary };
  });
  return changed > 0 ? { content: { ...content, trips }, changed } : { content, changed };
}
