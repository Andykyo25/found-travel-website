export function destinationGuide(slug: string): DestinationGuide | null {
  return guides[slug] ?? null;
}

/** 有指南的目的地代稱，給測試確認每一頁都有內容。 */
export const guidedDestinationSlugs = Object.keys(guides);

/** 從行程天數（「5日」「10日」）算出天數範圍與最常見的天數。 */
export function tripLengthSummary(destination: TripDestination) {
  const days = destination.trips
    .map((trip) => Number.parseInt(String(trip.days).replace(/[^\d]/g, ""), 10))
    .filter((value) => Number.isFinite(value) && value > 0);
  if (!days.length) return null;
  const counts = new Map<number, number>();
  for (const value of days) counts.set(value, (counts.get(value) ?? 0) + 1);
  const common = [...counts].sort((a, b) => b[1] - a[1] || a[0] - b[0])[0][0];
  return { min: Math.min(...days), max: Math.max(...days), common };
}

/** 每個目的地都有的問答：天數（資料計算）與客製包團。 */
export function destinationFaqs(destination: TripDestination): DestinationFaq[] {
  const guide = destinationGuide(destination.slug);
  const length = tripLengthSummary(destination);
  const faqs: DestinationFaq[] = [...(guide?.faqs ?? [])];
  if (length) {
    faqs.push({
      question: `${destination.name}行程大概要玩幾天？`,
      answer:
        length.min === length.max
          ? `目前的${destination.name}行程都是 ${length.min} 天。`
          : `目前的${destination.name}行程從 ${length.min} 天到 ${length.max} 天都有，最多的是 ${length.common} 天的行程。可以依假期長短與想去的地區挑選。`,
    });
  }
  faqs.push({
    question: `可以客製${destination.name}行程或親友包團嗎？`,
    answer: "可以。家庭出遊、親友自組或企業員工旅遊，都可以依人數、日期與預算調整行程與住宿。告訴 Yui 想去的地方和同行者的需求，我們會整理適合的安排再與你聯繫。",
  });
  return faqs;
}
